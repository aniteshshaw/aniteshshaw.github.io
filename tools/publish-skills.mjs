// ---------------------------------------------------------------- catalog + resolution
export function loadCatalog(file = DEFAULT_CATALOG) {
  if (!fs.existsSync(file)) {
    throw new Error(`Private catalog not found at ${file}\nRestore it from your backup, or set QIS_CATALOG=/path/to/catalog.json`);
  }
  const catalog = JSON.parse(fs.readFileSync(file, 'utf8'));
  validate(catalog);
  return catalog;
}

export function validate(catalog) {
  const errors = [];
  const ids = new Set();
  for (const s of catalog.skills || []) {
    if (!/^[a-z0-9-]+$/.test(s.id || '')) errors.push(`invalid id "${s.id}"`);
    if (ids.has(s.id)) errors.push(`duplicate id "${s.id}"`);
    ids.add(s.id);
    if (!STATUSES.includes(s.status)) errors.push(`${s.id}: status must be one of ${STATUSES.join(', ')}`);
    if (!CATEGORY[s.category]) errors.push(`${s.id}: category must be core, specialist, or utility`);
    if (s.publishAfter && !/^\d{4}-\d{2}-\d{2}$/.test(s.publishAfter)) errors.push(`${s.id}: publishAfter must be YYYY-MM-DD`);
    if (!Array.isArray(s.flow) || s.flow.length < 3 || s.flow.length > 6) errors.push(`${s.id}: flow needs 3–6 steps`);
  }
  if (errors.length) throw new Error('Catalog is invalid:\n  - ' + errors.join('\n  - '));
}

// The status a skill has on a given date: a scheduled date promotes it to live.
export function resolveStatus(skill, date = today()) {
  if (skill.publishAfter && skill.publishAfter <= date && skill.status !== 'live') return 'live';
  return skill.status;
}

export function plan(catalog, date = today()) {
  const skills = catalog.skills.slice().sort((a, b) => a.order - b.order)
    .map((s) => ({ ...s, resolved: resolveStatus(s, date) }));
  return {
    date,
    product: catalog.product,
    public: skills.filter((s) => s.resolved === 'live' || s.resolved === 'preview'),
    teaser: skills.filter((s) => s.resolved === 'coming-soon'),
    hidden: skills.filter((s) => s.resolved === 'hidden'),
    scheduled: skills.filter((s) => s.publishAfter && s.publishAfter > date)
  };
}

// ---------------------------------------------------------------- blueprint diagrams
// A "blueprint" is a hand-sketched flow: terminal → steps → terminal, with an animated
// packet travelling the line, each stage lighting up as it arrives, and one handwritten note.
let bpSeq = 0;
function blueprint({ nodes, startLabel, endLabel, note, sheet, linkPrefix = '' }) {
  const id = 'bp' + (++bpSeq);
  return blueprintH({ id, nodes, startLabel, endLabel, note, sheet, linkPrefix }) +
         blueprintV({ id: id + 'v', nodes, startLabel, endLabel, note, linkPrefix });
}


function svgDefs(id) {
  return `<defs>
    <pattern id="${id}-grid" width="24" height="24" patternUnits="userSpaceOnUse"><path d="M24 0H0v24" fill="none" class="bp-grid"/></pattern>
    <filter id="${id}-ink" x="-5%" y="-5%" width="110%" height="110%"><feTurbulence type="fractalNoise" baseFrequency="0.03" numOctaves="2" seed="7"/><feDisplacementMap in="SourceGraphic" scale="1.6"/></filter>
    <marker id="${id}-arr" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M1 1l8 4-8 4" fill="none" class="bp-arrowhead"/></marker>
  </defs>`;
}

function blueprintH({ id, nodes, startLabel, endLabel, note, sheet, linkPrefix }) {
  const W = 1100, H = sheet ? 330 : 300;
  const tx0 = 40, tx1 = W - 40, cy = 172;
  const n = nodes.length;
  const bw = n >= 6 ? 128 : 150, bh = 118;
  const x0 = 104, x1 = W - 104;
  const step = n > 1 ? (x1 - x0 - bw) / (n - 1) : 0;
  const boxes = nodes.map((nd, i) => ({ ...nd, x: x0 + i * step, cx: x0 + i * step + bw / 2 }));
  const linePath = `M${tx0} ${cy} H${tx1}`;
  let s = `<svg class="bp bp--h" data-axis="x" data-from="${tx0}" data-to="${tx1}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="${id}-t" xmlns="http://www.w3.org/2000/svg">
  <title id="${id}-t">${esc(nodes.map((nd, i) => `${i + 1}. ${nd.title}`).join(', '))}</title>${svgDefs(id)}
  <rect width="${W}" height="${H}" fill="url(#${id}-grid)"/>
  <g filter="url(#${id}-ink)">
    <path d="${linePath}" class="bp-line"/>
    <path d="${linePath}" class="bp-flow"/>
    <circle cx="${tx0}" cy="${cy}" r="20" class="bp-term"/>
    <circle cx="${tx1}" cy="${cy}" r="20" class="bp-term bp-term--end"/>
  </g>
  <g transform="translate(${tx0 - 9} ${cy - 9}) scale(.75)" class="bp-ico">${ICONS.chat}</g>
  <g transform="translate(${tx1 - 9} ${cy - 9}) scale(.75)" class="bp-ico bp-ico--end">${ICONS.check}</g>
  <text x="${tx0}" y="${cy + 44}" class="bp-term-label" text-anchor="middle">${esc(startLabel)}</text>
  <text x="${tx1}" y="${cy + 44}" class="bp-term-label" text-anchor="middle">${esc(endLabel)}</text>
  <circle r="7" cx="${tx0}" cy="${cy}" class="bp-packet"/>`;
  boxes.forEach((b, i) => {
    const title = clip(b.title, n >= 6 ? 14 : 16, 2);
    const sub = b.sub ? clip(b.sub, n >= 6 ? 15 : 18, 2) : [];
    const by = cy - bh / 2;
    const inner = `
    <g class="bp-node" data-a="${b.x}" data-b="${b.x + bw}">
      <rect x="${b.x}" y="${by}" width="${bw}" height="${bh}" rx="10" class="bp-box" filter="url(#${id}-ink)"/>
      <text x="${b.x + 14}" y="${by + 22}" class="bp-num">${String(i + 1).padStart(2, '0')}</text>
      ${b.icon ? `<g transform="translate(${b.x + bw - 32} ${by + 9}) scale(.8)" class="bp-ico">${ICONS[b.icon] || ''}</g>` : ''}
      ${title.map((t, k) => `<text x="${b.x + 14}" y="${by + 46 + k * 19}" class="bp-title">${esc(t)}</text>`).join('')}
      ${sub.map((t, k) => `<text x="${b.x + 14}" y="${by + 46 + title.length * 19 + 4 + k * 15}" class="bp-sub">${esc(t)}</text>`).join('')}
    </g>`;
    s += b.href ? `<a href="${linkPrefix}${b.href}" class="bp-link" aria-label="${esc(b.title)} — open skill">${inner}</a>` : inner;
    if (b.artifact) {
      s += `<text x="${b.cx}" y="${by + bh + 30}" class="bp-artifact" text-anchor="middle">→ ${esc(b.artifact)}</text>`;
    }
  });
  if (note && boxes[note.step - 1]) {
    const b = boxes[note.step - 1];
    const textX = Math.min(Math.max(b.cx + 10, 150), W - 170);
    const anchor = textX > W - 260 ? 'end' : 'start';
    const tX = anchor === 'end' ? Math.min(b.cx + 120, W - 24) : textX;
    s += `<text x="${tX}" y="58" class="bp-note" text-anchor="${anchor}">${esc(note.text)}</text>
    <path d="M${anchor === 'end' ? tX - 60 : tX + 14} 68 C ${b.cx + 26} 80, ${b.cx + 4} 88, ${b.cx} ${cy - bh / 2 - 8}" class="bp-note-arrow" marker-end="url(#${id}-arr)"/>`;
  }
  if (sheet) {
    s += `<g class="bp-sheet"><rect x="${W - 330}" y="${H - 34}" width="310" height="24" rx="3"/><text x="${W - 320}" y="${H - 17}">${esc(sheet)}</text></g>`;
  }
  return s + '</svg>';
}

function blueprintV({ id, nodes, startLabel, endLabel, note, linkPrefix }) {
  const W = 360, bw = 268, bh = 78, gap = 34, top = 74;
  const cx = 168, x = cx - bw / 2;
  const H = top + nodes.length * (bh + gap) + 52;
  const ty0 = 30, ty1 = H - 30;
  const linePath = `M${cx} ${ty0} V${ty1}`;
  let s = `<svg class="bp bp--v" data-axis="y" data-from="${ty0}" data-to="${ty1}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="${id}-t" xmlns="http://www.w3.org/2000/svg">
  <title id="${id}-t">${esc(nodes.map((nd, i) => `${i + 1}. ${nd.title}`).join(', '))}</title>${svgDefs(id)}
  <rect width="${W}" height="${H}" fill="url(#${id}-grid)"/>
  <g filter="url(#${id}-ink)">
    <path d="${linePath}" class="bp-line"/><path d="${linePath}" class="bp-flow"/>
    <circle cx="${cx}" cy="${ty0}" r="18" class="bp-term"/><circle cx="${cx}" cy="${ty1}" r="18" class="bp-term bp-term--end"/>
  </g>
  <g transform="translate(${cx - 8} ${ty0 - 8}) scale(.68)" class="bp-ico">${ICONS.chat}</g>
  <g transform="translate(${cx - 8} ${ty1 - 8}) scale(.68)" class="bp-ico bp-ico--end">${ICONS.check}</g>
  <text x="${cx + 28}" y="${ty0 + 5}" class="bp-term-label">${esc(startLabel)}</text>
  <text x="${cx + 28}" y="${ty1 + 5}" class="bp-term-label">${esc(endLabel)}</text>
  <circle r="6" cx="${cx}" cy="${ty0}" class="bp-packet"/>`;
  nodes.forEach((nd, i) => {
    const y = top + i * (bh + gap);
    const title = clip(nd.title, 26, 1);
    const sub = clip(nd.sub || (nd.artifact ? '→ ' + nd.artifact : ''), 30, 2);
    const inner = `<g class="bp-node" data-a="${y}" data-b="${y + bh}">
      <rect x="${x}" y="${y}" width="${bw}" height="${bh}" rx="10" class="bp-box" filter="url(#${id}-ink)"/>
      <text x="${x + 14}" y="${y + 24}" class="bp-num">${String(i + 1).padStart(2, '0')}</text>
      <text x="${x + 46}" y="${y + 25}" class="bp-title">${esc(title[0])}</text>
      ${sub.map((t, k) => `<text x="${x + 46}" y="${y + 46 + k * 15}" class="bp-sub">${esc(t)}</text>`).join('')}
    </g>`;
    s += nd.href ? `<a href="${linkPrefix}${nd.href}" class="bp-link" aria-label="${esc(nd.title)} — open skill">${inner}</a>` : inner;
    if (note && note.step === i + 1) {
      s += `<text x="${W - 8}" y="${y - 9}" class="bp-note bp-note--sm" text-anchor="end">${esc(note.text)}</text>`;
    }
  });
  return s + '</svg>';
}

