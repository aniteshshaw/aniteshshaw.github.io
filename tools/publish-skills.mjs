function replaceRegion(html, name, content, file) {
  const re = new RegExp(`(<!-- qis:begin ${name} -->)[\\s\\S]*?(<!-- qis:end ${name} -->)`);
  if (!re.test(html)) throw new Error(`${file}: missing region markers for "${name}"`);
  return html.replace(re, `$1\n${content}\n$2`);
}

function replaceCounts(html, counts) {
  return html.replace(/(<span data-qis="([a-z-]+)">)[^<]*(<\/span>)/g, (m, open, key, close) =>
    counts[key] !== undefined ? open + counts[key] + close : m);
}

function sitemap(publicSkills, date) {
  const urls = ['/', '/qis-skills/', '/personal/', '/resume/', ...publicSkills.map((s) => `/qis-skills/${s.id}/`)];
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${SITE}${u}</loc><lastmod>${date}</lastmod></url>`).join('\n')}
</urlset>
`;
}

// ---------------------------------------------------------------- publish
export function publish({ catalogPath = DEFAULT_CATALOG, date = today(), dryRun = false } = {}) {
  bpSeq = 0;
  const catalog = loadCatalog(catalogPath);
  const p = plan(catalog, date);
  const core = p.public.filter((s) => s.category === 'core');
  const ctx = { publicSkills: p.public, core, version: catalog.product?.version || '1.0' };
  const written = [];
  const removed = [];

  if (!dryRun) {
    // 1. Product page regions
    const productFile = path.join(ROOT, 'qis-skills', 'index.html');
    let html = fs.readFileSync(productFile, 'utf8');
    html = replaceRegion(html, 'stats', regionStats(p, core), productFile);
    html = replaceRegion(html, 'pipeline', regionPipeline(core), productFile);
    html = replaceRegion(html, 'catalog', regionCatalog(p), productFile);
    html = replaceRegion(html, 'roadmap', regionRoadmap(p), productFile);
    html = replaceRegion(html, 'demos', regionDemo(p), productFile);
    fs.writeFileSync(productFile, html);
    written.push('qis-skills/index.html');

    const homeFile = path.join(ROOT, 'index.html');
    fs.writeFileSync(homeFile, replaceRegion(fs.readFileSync(homeFile, 'utf8'), 'home-pipeline', regionHomePipeline(core), homeFile));
    written.push('index.html');

    // 2. One page per public skill
    for (const s of p.public) {
      const dir = path.join(ROOT, 'qis-skills', s.id);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'index.html'), skillPage(s, ctx));
      written.push(`qis-skills/${s.id}/index.html`);
    }

    // 3. Remove pages for skills that are no longer public (only ones this script generated)
    const keep = new Set(p.public.map((s) => s.id));
    for (const entry of fs.readdirSync(path.join(ROOT, 'qis-skills'), { withFileTypes: true })) {
      if (!entry.isDirectory() || keep.has(entry.name)) continue;
      const f = path.join(ROOT, 'qis-skills', entry.name, 'index.html');
      if (fs.existsSync(f) && fs.readFileSync(f, 'utf8').includes(GENERATED_MARK)) {
        fs.rmSync(path.join(ROOT, 'qis-skills', entry.name), { recursive: true });
        removed.push(`qis-skills/${entry.name}/`);
      }
    }

    // 4. Live counts on every page that shows them
    const counts = { 'live-count': p.public.length, 'core-count': core.length };
    for (const rel of ['index.html', 'personal/index.html', 'qis-skills/index.html', 'resume/index.html']) {
      const f = path.join(ROOT, rel);
      const before = fs.readFileSync(f, 'utf8');
      const after = replaceCounts(before, counts);
      if (after !== before) { fs.writeFileSync(f, after); if (!written.includes(rel)) written.push(rel); }
    }

    // 5. Sitemap
    fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap(p.public, date));
    written.push('sitemap.xml');
  }

  return {
    date,
    public: p.public.map((s) => ({ id: s.id, name: s.name, status: s.resolved, featured: !!s.featured })),
    teaser: p.teaser.map((s) => ({ id: s.id, name: s.name, publishAfter: s.publishAfter })),
    hidden: p.hidden.map((s) => ({ id: s.id, name: s.name, publishAfter: s.publishAfter })),
    scheduled: p.scheduled.map((s) => ({ id: s.id, name: s.name, publishAfter: s.publishAfter, status: s.status })),
    written, removed
  };
}

export function formatSummary(r, dryRun) {
  const lines = [];
  lines.push(`QIS-Skills ${dryRun ? 'preview' : 'publish'} as of ${r.date}`);
  lines.push(`  Public  (${r.public.length}): ${r.public.map((s) => s.name + (s.featured ? ' ★' : '') + (s.status === 'preview' ? ' [preview]' : '')).join(', ') || '—'}`);
  lines.push(`  Teased  (${r.teaser.length}): ${r.teaser.map((s) => `${s.name}${s.publishAfter ? ' → ' + s.publishAfter : ''}`).join(', ') || '—'}`);
  lines.push(`  Private (${r.hidden.length}): ${r.hidden.map((s) => `${s.name}${s.publishAfter ? ' → ' + s.publishAfter : ''}`).join(', ') || '—'}  (never written to the site)`);
  if (r.scheduled.length) lines.push(`  Scheduled: ${r.scheduled.map((s) => `${s.name} goes live ${s.publishAfter}`).join('; ')}`);
  if (!dryRun) {
    lines.push(`  Wrote ${r.written.length} files${r.removed.length ? `, removed ${r.removed.join(', ')}` : ''}.`);
    lines.push('  Next: review locally, then commit and push.');
  }
  return lines.join('\n');
}

